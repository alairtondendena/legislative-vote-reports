"""End-to-end checks on the sample dataset.

The files in ``tests/expected/`` were written by hand from the input CSVs (cross-checked
with awk), not generated by this code, so they are an independent reference.
"""

import csv
from pathlib import Path

import pytest

from vote_reports.cli import BILLS_REPORT, LEGISLATORS_REPORT, generate_reports

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
EXPECTED_DIR = ROOT / "tests" / "expected"
REPORTS = [LEGISLATORS_REPORT, BILLS_REPORT]


@pytest.fixture(scope="module")
def out_dir(tmp_path_factory: pytest.TempPathFactory) -> Path:
    out = tmp_path_factory.mktemp("output")
    generate_reports(DATA_DIR, out)
    return out


def rows_by_id(path: Path) -> dict[str, dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as file:
        return {row["id"]: row for row in csv.DictReader(file)}


@pytest.mark.parametrize("report", REPORTS)
def test_report_matches_hand_written_expected_file(out_dir: Path, report: str) -> None:
    assert (out_dir / report).read_text(encoding="utf-8") == (EXPECTED_DIR / report).read_text(
        encoding="utf-8"
    )


@pytest.mark.parametrize("report", REPORTS)
def test_committed_output_is_up_to_date(out_dir: Path, report: str) -> None:
    assert (ROOT / "output" / report).read_text(encoding="utf-8") == (out_dir / report).read_text(
        encoding="utf-8"
    )


def test_sponsor_missing_from_legislators_is_unknown(out_dir: Path) -> None:
    infrastructure_bill = rows_by_id(out_dir / BILLS_REPORT)["2900994"]
    assert infrastructure_bill["primary_sponsor"] == "Unknown"


def test_legislator_without_votes_is_reported_with_zero_counts(out_dir: Path) -> None:
    yarmuth = rows_by_id(out_dir / LEGISLATORS_REPORT)["412211"]
    assert (yarmuth["num_supported_bills"], yarmuth["num_opposed_bills"]) == ("0", "0")


def test_sample_data_produces_no_warnings(tmp_path: Path, caplog: pytest.LogCaptureFixture) -> None:
    generate_reports(DATA_DIR, tmp_path)
    assert caplog.records == []
